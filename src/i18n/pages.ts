export type PageKey = Key;

export function pageT(lang: UiLang, key: PageKey, params?: Record<string, string | number>): string {
  const s = (lang === 'ru' ? ru : en)[key] ?? key;
  return params
    ? s.replace(/\{(\w+)\}/g, (m, k: string) => (params[k] !== undefined ? String(params[k]) : m))
    : s;
}
